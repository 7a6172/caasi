def test_mapping_inspect_bad_yaml(runner, tmp_path):
    not_a_map = tmp_path / "list.yaml"
    not_a_map.write_text("- one\n- two\n", encoding="utf-8")
    result = runner.invoke(app, ["mapping", "inspect", str(not_a_map)])
    assert result.exit_code == 1
    assert "Not a readable map YAML" in all_output(result)
    assert "does not contain a mapping" in all_output(result)


def test_mapping_run_starts_tracked_run(runner, fake_ros_world, tmp_path, monkeypatch):
    runs_base = configure_runs(tmp_path, monkeypatch)
    fake_ros_world.packages("isaac_ros_nvblox")
    result = runner.invoke(app, ["mapping", "run", "--name", "nvblox"])
    assert result.exit_code == 0, all_output(result)
    run_dir = wait_for_run(runs_base)
    manifest = yaml.safe_load((run_dir / "manifest.yaml").read_text(encoding="utf-8"))
    assert manifest["kind"] == "mapping"
    assert manifest["name"] == "nvblox"
    assert manifest["command"][-2:] == ["isaac_ros_nvblox", "nvblox.launch.py"]
    stdout = (run_dir / "stdout.log").read_text(encoding="utf-8")
    assert stdout.strip() == "launch isaac_ros_nvblox nvblox.launch.py"


def test_mapping_run_needs_launch_file(runner, fake_ros_world):
    fake_ros_world.packages("nav2_map_server")
    result = runner.invoke(app, ["mapping", "run", "--backend", "map_saver"])
    assert result.exit_code == 1
    assert "No launch file is defined for 'map_saver' in domain 'mapping'." in all_output(result)


def test_mapping_status(runner, fake_ros_world):
    fake_ros_world.packages("isaac_ros_nvblox")
    result = runner.invoke(app, ["mapping", "status", "--json"])
    assert result.exit_code == 0, all_output(result)
    data = json.loads(result.output)
    assert data["domain"] == "mapping"
    assert data["total"] == 3
    assert data["installed"] == 1
    assert data["running"] == []
    states = {item["key"]: item for item in data["capabilities"]}
    assert states["nvblox"]["found"] is True
    assert states["map_saver"]["core"] is True
    assert states["map_saver"]["found"] is False

    result = runner.invoke(app, ["mapping", "status"])
    assert result.exit_code == 0, all_output(result)
    assert "1 of 3 capabilities installed." in result.output
